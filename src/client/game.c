#include "game.h"

void printGame(Game *game)
{
    printf("Grenier du joueur 1: %d\n\n", game->hands[0]);
    printf("*-----------------------------------------------------------------------------------------------*\n"
           "|                                                                                               |\n");
    for (int i = 0; i < 12; i++)
    {
        printf("|\t%2d\t", game->board[i]);
        if (i == 5)
            printf("|\n"
                   "|                                                                                               |\n"
                   "*-----------------------------------------------------------------------------------------------*\n"
                   "|                                                                                               |\n");
    }
    printf("|\n");
    printf("|                                                                                               |\n"
           "*-----------------------------------------------------------------------------------------------*\n");
    printf("\nGrenier du joueur 2: %d\n", game->hands[1]);
}
